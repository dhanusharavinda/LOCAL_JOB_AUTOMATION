/**
 * Read the user's resume as plain text. Returns null if no resume has
 * been uploaded yet. This is the single source of truth for resume
 * text across the whole app (settings modal, pipeline, resume-analyze).
 */
export async function downloadResumeText(userId: string): Promise<string | null> {
  const admin = getAdmin();
  if (!admin) return null;
  const { data, error } = await admin.storage
    .from(RESUME_BUCKET)
    .download(`${userId}/resume.txt`);
  if (error || !data) return null;
  return await data.text();
}

export async function downloadResumeMeta(userId: string): Promise<string | null> {
  const admin = getAdmin();
  if (!admin) return null;
  const { data, error } = await admin.storage
    .from(RESUME_BUCKET)
    .download(`${userId}/resume.meta`);
  if (error || !data) return null;
  return (await data.text()).trim();
}

/**
 * Delete every resume-related file for a user (text, meta, original).
 * Called when the user clicks "Remove uploaded resume" in Settings.
 */
export async function deleteResumeFiles(userId: string): Promise<void> {
  const admin = getAdmin();
  if (!admin) throw new Error("Storage is not configured on the server");
  // We don't know the original extension, so we list everything in the
  // user's folder and remove whatever matches.
  const { data: list } = await admin.storage.from(RESUME_BUCKET).list(userId);
  if (!list || list.length === 0) return;
  const paths = list
    .filter((f) => f.name.startsWith("resume"))
    .map((f) => `${userId}/${f.name}`);
  if (paths.length === 0) return;
  const { error } = await admin.storage.from(RESUME_BUCKET).remove(paths);
  if (error) throw error;
}

// ─── Tailored PDFs ───────────────────────────────────────────────────

/**
 * Upload a pipeline-generated tailored resume PDF. Lives at
 * `{userId}/{filename}.pdf`. Returns a signed URL valid for 7 days so
 * the kanban card can link directly to the file.
 */
export async function uploadResumePdf(
  userId: string,
  filename: string,
  buffer: Buffer
): Promise<{ path: string; signedUrl: string }> {
  const admin = getAdmin();
  if (!admin) throw new Error("Storage is not configured on the server");
  const safeName = filename.replace(/[^a-zA-Z0-9._-]/g, "_");
  const path = `${userId}/${safeName}`;
  const { error: uploadError } = await admin.storage
    .from(PDF_BUCKET)
    .upload(path, buffer, {
      contentType: "application/pdf",
      upsert: true,
    });
  if (uploadError) throw uploadError;

  const { data, error: signError } = await admin.storage
    .from(PDF_BUCKET)
    .createSignedUrl(path, 60 * 60 * 24 * 7); // 7 days
  if (signError || !data?.signedUrl) {
    throw signError || new Error("Failed to create signed URL");
  }
  return { path, signedUrl: data.signedUrl };
}

/**
 * Generate a fresh signed URL for an already-uploaded PDF. Used when a
 * previously-saved signed URL has expired and the client wants to
 * re-download the file.
 */
export async function getResumePdfSignedUrl(userId: string, filename: string): Promise<string | null> {
  const admin = getAdmin();
  if (!admin) return null;
  const safeName = filename.replace(/[^a-zA-Z0-9._-]/g, "_");
  const { data, error } = await admin.storage
    .from(PDF_BUCKET)
    .createSignedUrl(`${userId}/${safeName}`, 60 * 60 * 24 * 7);
  if (error || !data?.signedUrl) return null;
  return data.signedUrl;
}
